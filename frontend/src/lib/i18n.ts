export type TKey = keyof typeof zhCN
export const DICTS: Record<Lang, Dict> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en }
export const LANG_LABEL: Record<Lang, string> = { 'zh-CN': '简体中文', 'zh-TW': '繁體中文', en: 'English' }
export const LANG_SHORT: Record<Lang, string> = { 'zh-CN': '简', 'zh-TW': '繁', en: 'EN' }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS['zh-CN'][key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export function errorKey(code: string): TKey {
  const k = `err.${code}` as TKey
  return k in zhCN ? k : 'err.unknown'
}
